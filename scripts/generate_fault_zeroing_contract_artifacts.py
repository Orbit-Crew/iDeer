"""Generate the sandbox-side fault-zeroing Result Contract artifacts.

The contract module (``backend/app/agentplatform/fault_zeroing/contract.py``)
is the single source of the declarative Result Contract content.  This script
derives both sandbox-side artifacts from it, so one rule change is one source
edit plus this one command (ticket 07, spec candidate 6, Q10=a):

- ``resources/skills/fault-zeroing/scripts/validate_fault_zeroing_outputs.py``
  — the stdlib-only offline validator with the contract module embedded
  verbatim (the sandbox cannot import ``app.*``, so the embedded copy stays
  the established policy, ADR-0004);
- ``resources/skills/fault-zeroing/references/result_contract.md`` — the
  sandbox-readable citation target that workflow prompts and the SKILL/SOUL
  texts reference instead of restating the lists.

Usage::

    python3 scripts/generate_fault_zeroing_contract_artifacts.py          # regenerate
    python3 scripts/generate_fault_zeroing_contract_artifacts.py --check  # exit 1 on drift

The source is validated before anything is written: the contract module must
compile, start with its module docstring, and expose the full contract
surface; a malformed source fails loudly and leaves no partial artifacts.
"""

